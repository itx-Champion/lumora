"use client"

import { useState } from "react"
import { Loader2, RefreshCw, Sparkles } from "lucide-react"
import { motion } from "motion/react"
import { toast } from "sonner"
import { Markdown } from "@/components/chat/markdown"
import { cn } from "@/lib/utils"

type Result = { text: string; mode: "gemini" | "groq" | "demo"; model: string }

/** A button that asks the CRM AI endpoint for a briefing or summary and renders it in place. */
export function AiInsight({
  task,
  id,
  label,
  description,
  className,
}: {
  task: "briefing" | "contact-summary"
  id?: string
  label: string
  description: string
  className?: string
}) {
  const [result, setResult] = useState<Result | null>(null)
  const [loading, setLoading] = useState(false)

  const run = async () => {
    setLoading(true)
    try {
      const res = await fetch("/api/crm/ai", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ task, id }),
      })
      const data = await res.json()
      if (!res.ok) throw new Error(data.error ?? "The AI request failed.")
      setResult(data)
    } catch (error) {
      toast.error(error instanceof Error ? error.message : "The AI request failed.")
    } finally {
      setLoading(false)
    }
  }

  return (
    <div className={cn("relative overflow-hidden rounded-2xl border bg-card/60 p-5 shadow-sm", className)}>
      <div className="pointer-events-none absolute -top-24 -right-16 size-56 rounded-full bg-violet/15 blur-3xl" />
      <div className="relative flex flex-wrap items-start gap-3">
        <span className="flex size-9 shrink-0 items-center justify-center rounded-xl bg-[linear-gradient(135deg,var(--brand-violet),var(--brand-cyan))] text-white shadow-md shadow-violet/25">
          <Sparkles className="size-4" />
        </span>
        <div className="min-w-0 flex-1">
          <p className="font-semibold">{label}</p>
          <p className="text-sm text-muted-foreground">{description}</p>
        </div>
        <button
          onClick={run}
          disabled={loading}
          className="flex h-9 items-center gap-1.5 rounded-lg border bg-background/70 px-3 text-sm font-medium transition-colors hover:border-violet/40 disabled:opacity-60"
        >
          {loading ? <Loader2 className="size-3.5 animate-spin" /> : result ? <RefreshCw className="size-3.5" /> : <Sparkles className="size-3.5 text-violet" />}
          {loading ? "Thinking…" : result ? "Regenerate" : "Generate"}
        </button>
      </div>
      {loading && !result && (
        <div className="relative mt-4 space-y-2">
          {[92, 78, 85].map((w) => (
            <div key={w} className="h-3 animate-pulse rounded bg-foreground/8" style={{ width: `${w}%` }} />
          ))}
        </div>
      )}
      {result && (
        <motion.div initial={{ opacity: 0, y: 6 }} animate={{ opacity: 1, y: 0 }} className={cn("relative mt-4 text-sm", loading && "opacity-50")}>
          <Markdown text={result.text} sources={[]} onCite={() => {}} />
          <p className="mt-3 font-mono text-[10px] tracking-wide text-muted-foreground uppercase">
            {result.mode === "demo" ? "Generated from your CRM data without a model (no API key or quota)" : `Generated by ${result.model} from live CRM data`}
          </p>
        </motion.div>
      )}
    </div>
  )
}
